"""Put every run in results/ into ONE table (results/REPORT.md), so the numbers in your note are copied by a script, not by hand.

  python scripts/make_report.py

Shows the automatic score and, when you have filled the manual_grade column of answers.csv (1 = right, 0 = wrong),
the manual score too. Quote the manual score in the note if you have it: it is the one a person would agree with.
"""
import _bootstrap  # noqa: F401

import argparse
import csv
import json
import sys
from pathlib import Path

from nirbhor.config import RESULTS_DIR


def manual_score(run_dir: Path) -> str:
    path = run_dir / "answers.csv"
    if not path.exists():
        return "n/a"
    with open(path, newline="", encoding="utf-8-sig") as f:
        grades = [(r.get("manual_grade") or "").strip() for r in csv.DictReader(f)]
    graded = [g for g in grades if g in ("0", "1")]
    return f"{sum(g == '1' for g in graded)}/{len(graded)}" if graded else "not graded yet"


def frac(m: dict, a: str, b: str) -> str:
    return f"{m[a]}/{m[b]}" if a in m and b in m else "n/a"


def seconds(ms) -> str:
    return f"{ms / 1000:.2f}" if ms else "n/a"


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--results-dir", type=Path, default=RESULTS_DIR)
    a = ap.parse_args()
    runs = []
    for f in sorted(a.results_dir.glob("*/metrics.json")):
        d = json.loads(f.read_text(encoding="utf-8"))
        runs.append((f.parent, d.get("meta", {}), d["metrics"]))
    if not runs:
        sys.exit("No results yet. Run scripts/run_eval.py first.")

    head = ["Run", "Question set", "Answer model", "Embeddings", "Judge", "Auto: correct", "Manual: correct",
            "In-scope right", "\"I don't know\" right", "False \"I don't know\"", "False answers",
            "English", "Bangla", "Banglish", "Median s", "p95 s", "Fell back to FAQ text", "Hardware"]
    lines = ["# Results (generated by scripts/make_report.py)", "",
             "Automatic scoring is lenient; read answers.csv and use the manual column for the final numbers.", "",
             "| " + " | ".join(head) + " |", "|" + "---|" * len(head)]
    for d, meta, m in runs:
        bl = m.get("by_language", {})
        lang = lambda k: f"{bl[k]['correct']}/{bl[k]['total']}" if k in bl else "n/a"  # noqa: E731
        judge = meta.get("use_judge")
        judge = "n/a" if judge is None else ("yes+examples" if meta.get("judge_examples") else "yes" if judge else "no")
        emb = meta.get("embed_model")
        cells = [
            d.name, meta.get("question_set", "40 given questions"), meta.get("gen_model") or meta.get("label", "n/a"),
            emb if emb else ("keywords only" if "use_judge" in meta else "n/a"), judge,
            frac(m, "correct", "total"), manual_score(d), frac(m, "in_scope_correct", "in_scope"),
            frac(m, "idk_correct", "out_of_scope"), str(m.get("false_idk", "n/a")), str(m.get("false_answer", "n/a")),
            lang("en"), lang("bn"), lang("banglish"),
            seconds(m["latency_ms"]["median"]), seconds(m["latency_ms"]["p95"]),
            str(m.get("fallback_to_faq_text", "n/a")), meta.get("hardware", "n/a"),
        ]
        lines.append("| " + " | ".join(cells) + " |")
    out = a.results_dir / "REPORT.md"
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("\n".join(lines))
    print(f"\nwritten to {out}")


if __name__ == "__main__":
    main()
